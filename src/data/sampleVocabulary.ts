export function buildSamplePackEntries(packId: string): {
  collection: VocabularyCollection;
  entries: VocabularyEntry[];
} | null {
  const pack = OPTIONAL_SAMPLE_PACKS.find((p) => p.collection.id === packId);
  if (!pack) return null;
  const now = new Date().toISOString();
  const collection: VocabularyCollection = {
    ...pack.collection,
    createdAt: now,
  };
  const entries: VocabularyEntry[] = pack.entries.map((item, idx) => ({
    id: `${packId}_w_${idx + 1}`,
    word: item.word,
    meaning: item.meaning,
    partOfSpeech: item.partOfSpeech,
    ipa: item.ipa,
    example: item.example,
    difficulty: item.difficulty,
    topic: item.topic,
    source: item.source,
    notes: '',
    status: 'New',
    collectionIds: [collection.id],
    createdAt: now,
    updatedAt: now,
    stats: {
      attempts: 0,
      correct: 0,
      incorrect: 0,
      needsReview: false,
    },
  }));
  return { collection, entries };
}
